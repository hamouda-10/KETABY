export interface BookPage {
  chapter?: string;
  heading?: string;
  paragraphs: string[];
  quote?: string;
  pageNumber: number;
}

export interface BookPalette {
  coverBg: string;
  spineBg: string;
  ink: string;
  accent: string;
  motif: 'arch' | 'star' | 'wave' | 'botanical' | 'compass' | 'dome' | 'moon' | 'columns';
}

export interface Book {
  id: string;
  index: number;
  title: string;
  author: string;
  subtitle: string;
  year: number;
  genre: string;
  editionNote: string;
  palette: BookPalette;
  pages: BookPage[];
}

export interface JournalArticle {
  date: string;
  title: string;
  excerpt: string;
}

const ARABIC_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

export function toArabicDigits(value: number | string): string {
  return String(value).replace(/\d/g, (d) => ARABIC_DIGITS[Number(d)]);
}

function makeBookPages(
  title: string,
  author: string,
  genre: string,
  year: number,
  intro: string,
  ch1Title: string,
  ch1Body: string[],
  quote1: string,
  ch2Title: string,
  ch2Body: string[],
  ch3Title: string,
  ch3Body: string[],
  closingNote: string
): BookPage[] {
  const safeCh1 = ch1Body.length >= 3 ? ch1Body : [...ch1Body, ch1Body[0] || intro];
  const safeCh2 = ch2Body.length >= 2 ? ch2Body : [...ch2Body, intro];
  const safeCh3 = ch3Body.length >= 2 ? ch3Body : [...ch3Body, closingNote];

  return [
    {
      chapter: 'الاستهلال',
      heading: title,
      paragraphs: [
        `تأليف: ${author}`,
        `التصنيف: ${genre} · طبعة عام ${toArabicDigits(year)}`,
        intro,
      ],
      quote: quote1,
      pageNumber: 1,
    },
    {
      chapter: 'الفصل الأول',
      heading: ch1Title,
      paragraphs: safeCh1.slice(0, 2),
      pageNumber: 2,
    },
    {
      heading: `تتمة: ${ch1Title}`,
      paragraphs: safeCh1.slice(2),
      quote: quote1,
      pageNumber: 3,
    },
    {
      chapter: 'الفصل الثاني',
      heading: ch2Title,
      paragraphs: safeCh2.slice(0, 2),
      pageNumber: 4,
    },
    {
      heading: `تتمة: ${ch2Title}`,
      paragraphs: safeCh2.slice(2).length > 0 ? safeCh2.slice(2) : [safeCh2[safeCh2.length - 1]],
      pageNumber: 5,
    },
    {
      chapter: 'الفصل الثالث',
      heading: ch3Title,
      paragraphs: [safeCh3[0]],
      pageNumber: 6,
    },
    {
      heading: `خاتمة: ${ch3Title}`,
      paragraphs: safeCh3.slice(1),
      quote: quote1,
      pageNumber: 7,
    },
    {
      chapter: 'خاتمة النسخة',
      heading: 'بيان الطبع والأرشيف',
      paragraphs: [
        closingNote,
        `نُقل هذا النص إلى خزانة مكتبة الرقعة بخط واضح ومقروء من طبعة سنة ${toArabicDigits(year)}م، لتصفحها ككتاب ورقي أصيل بصفحتين متقابلتين.`,
      ],
      pageNumber: 8,
    },
  ];
}

